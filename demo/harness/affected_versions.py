"""Compute the AFFECTED VERSIONS (informally: blast radius) of a rule or a material reference.

Given assembly records, list every assembled assistant whose active rule list inherits a rule
(tier/rule-id) or whose materials include a reference (tier/material-ref). Evidence is attributed
to assembly records, never to bare tiers, so the computation runs over records, not configs.

Usage (from demo/):
  python3 -I harness/affected_versions.py --assemblies out/assemblies/asm-*-0001.json \
      --query H/H-R03 --query H1/hargreaves-rta-ch4 --out out/affected_versions.md
Executed demonstration: deterministic; no model is called.
"""
import argparse
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))  # needed under python3 -I
from common import md_table, now_iso, write_text  # noqa: E402

THREE_QUESTIONS = (
    "Discovery location, cause location, and affected versions are three different questions. "
    "Both fictional reports in this demonstration were DISCOVERED in H1 (comment tier, attributed to asm-H1-0001). "
    "For CP-0001 the CAUSE is located one tier up, in H (rule H-R03), and the AFFECTED VERSIONS are every "
    "assembled assistant that inherits that rule — H1 and H2, but not S1 (a different subject branch) and not the "
    "U-only baseline (which never had the rule). For CP-0002 the cause is located where it was discovered — a local "
    "H1 material reference — so the affected set is H1 alone, even though the symptom (fabricating unavailable "
    "material) is one the university-level retained test SC-U-003 already covers and passes elsewhere. The first "
    "finding justifies a change to shared guidance that must be tested on both courses; the second must stay local, "
    "and a harness that could only reason about the discovering course would get one of the two wrong.")


def load_records(paths):
    return [json.load(open(p, encoding="utf-8")) for p in paths]


def chain_ids(record):
    return [t["id"] for t in record["tier_versions"]]


def inherits(record, tier_id, item):
    """True if the assembly has an ACTIVE rule `item` contributed by tier `tier_id`, or a material `item`
    contributed by tier `tier_id`. Returns (kind, matched) where kind is 'rule', 'material' or None."""
    for r in record["rules"]:
        if r["rule_id"] == item and r["tier"].split("@")[0] == tier_id:
            return "rule", r["active"]
    for m in record["materials"]:
        if m["ref"] == item and m["tier"].split("@")[0] == tier_id:
            return "material", True
    return None, False


def affected_versions(records, tier_id, item):
    """Return {'affected': [...], 'unaffected': [...], 'kind': 'rule'|'material'} over the given records."""
    out, kind_seen = {"affected": [], "unaffected": []}, None
    for rec in records:
        kind, hit = inherits(rec, tier_id, item)
        kind_seen = kind_seen or kind
        entry = {"assembly_id": rec["assembly_id"], "target": rec["target"],
                 "chain": " <- ".join(f"{t['id']}@{t['version']}" for t in reversed(rec["tier_versions"]))}
        out["affected" if hit else "unaffected"].append(entry)
    out["kind"] = kind_seen or "unknown"
    return out


def render(records, queries):
    lines = ["# Affected-versions report (executed demonstration)", "",
             f"Generated by harness/affected_versions.py at {now_iso()} over "
             f"{len(records)} assembly records: " + ", ".join(r["assembly_id"] for r in records) + ".", "",
             "All configurations are fictional (Wrenfield University). An assembly is *affected* by a rule when the "
             "rule is present and active in its ordered rule list with provenance from the named tier; by a material "
             "when the reference is present in its materials list from the named tier.", ""]
    for q in queries:
        tier_id, item = q.split("/", 1)
        res = affected_versions(records, tier_id, item)
        lines += [f"## Query: {tier_id} / {item}  ({res['kind']})", "",
                  f"Affected versions: **{{{', '.join(e['target'] for e in res['affected']) or 'none'}}}** "
                  f"({len(res['affected'])} of {len(records)} assemblies)", "",
                  md_table(["assembly", "target", "tier chain (course <- subject <- university)", "inherits?"],
                           [(e["assembly_id"], e["target"], e["chain"], "yes") for e in res["affected"]]
                           + [(e["assembly_id"], e["target"], e["chain"], "no") for e in res["unaffected"]]), ""]
    lines += ["## Why three questions, not one", "", THREE_QUESTIONS, ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--assemblies", nargs="+", required=True)
    ap.add_argument("--query", action="append", required=True, help="TIER/RULE_ID or TIER/MATERIAL_REF")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    records = load_records(a.assemblies)
    write_text(a.out, render(records, a.query))
    for q in a.query:
        res = affected_versions(records, *q.split("/", 1))
        print(f"{q}: affected = {{{', '.join(e['target'] for e in res['affected'])}}}")


if __name__ == "__main__":
    main()
